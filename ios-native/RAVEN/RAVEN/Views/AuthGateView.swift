import SwiftUI

// MARK: - Auth Gate (Serverless key-based identity)
//
// Messenger pivot: there is NO server account. The device's Ed25519 keypair
// (DeviceIdentityService) IS the identity. The only "registration" step is
// choosing a local display name. Flow: splash → onboarding → display name →
// main. The legacy email/password, OAuth, OTP and phone screens were removed.
struct AuthGateView: View {
    @State private var authService = AuthService.shared
    @AppStorage("hasSeenOnboarding") private var hasSeenOnboarding: Bool = false

    var body: some View {
        Group {
            // Priority 0: splash while the local identity loads from Keychain.
            if authService.bootState == .checking {
                LaunchView()
            }
            // Priority 1: first-run onboarding (once ever).
            else if !hasSeenOnboarding {
                OnboardingView {
                    withAnimation(.spring(response: 0.5)) {
                        hasSeenOnboarding = true
                    }
                }
            }
            // Priority 2: the ONLY registration step — pick a display name.
            else if !authService.hasChosenLocalDisplayName {
                NavigationStack {
                    DisplayNameSetupView()
                }
            }
            // Priority 3: in. The on-device keypair is the identity.
            else {
                #if targetEnvironment(macCatalyst)
                RavenMacShell()
                #else
                MainShellView()
                #endif
            }
        }
        .onAppear {
            Task {
                if authService.bootState == .checking {
                    await authService.checkExistingSession()
                }
            }
        }
    }
}

// MARK: - Display Name Setup (serverless registration)
/// The entire "sign up" flow: choose a display name. The identity is the
/// device keypair generated by DeviceIdentityService — no server, no email,
/// no password, no phone.
struct DisplayNameSetupView: View {
    @State private var authService = AuthService.shared
    @State private var name: String = ""
    @State private var isSubmitting = false
    @State private var errorText: String?
    @FocusState private var focused: Bool

    private var trimmed: String {
        name.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    var body: some View {
        VStack(spacing: 28) {
            Spacer()

            // TERMINAL REDESIGN: identity creation as a console session.
            Image("RavenLogo")
                .resizable()
                .scaledToFit()
                .frame(width: 72, height: 72)
                .clipShape(RoundedRectangle(cornerRadius: DS.radiusInner, style: .continuous))
                .overlay(
                    RoundedRectangle(cornerRadius: DS.radiusInner, style: .continuous)
                        .strokeBorder(DS.hairline, lineWidth: 1)
                )
                .shadow(color: DS.phosphor.opacity(0.3), radius: 14)

            VStack(spacing: 8) {
                Text("$ raven --new-identity")
                    .font(.system(.title3, design: .monospaced, weight: .bold))
                    .foregroundStyle(DS.mist)

                Text("this is how people see you. no account, no email, no phone — your identity is a key that lives only on this device.")
                    .font(.system(.footnote, design: .monospaced))
                    .foregroundStyle(.secondary)
                    .multilineTextAlignment(.center)
                    .padding(.horizontal, 24)
            }

            LiquidGlassTextField(icon: "person", placeholder: "display name", text: $name)
                .focused($focused)
                .submitLabel(.done)
                .onSubmit(submit)
                .padding(.horizontal, 24)

            Button(action: submit) {
                HStack(spacing: 8) {
                    if isSubmitting { ProgressView().tint(DS.ink) }
                    Text(isSubmitting ? "[ generating… ]" : "[ enter ]")
                        .font(.system(.callout, design: .monospaced, weight: .bold))
                }
                .foregroundStyle(DS.ink)
                .frame(maxWidth: .infinity)
                .padding()
                .background(
                    trimmed.isEmpty
                        ? AnyShapeStyle(Color.gray.opacity(0.4))
                        : AnyShapeStyle(DS.phosphor)
                )
                .clipShape(RoundedRectangle(cornerRadius: DS.radiusInner, style: .continuous))
            }
            .disabled(trimmed.isEmpty || isSubmitting)
            .padding(.horizontal, 24)

            if let errorText {
                Text("[!!] " + errorText)
                    .font(.system(.footnote, design: .monospaced))
                    .foregroundStyle(DS.accentDanger)
                    .multilineTextAlignment(.center)
                    .padding(.horizontal, 24)
                    .transition(.opacity)
            }

            Spacer()
        }
        .navigationBarHidden(true)
        .onAppear { focused = true }
    }

    private func submit() {
        guard !trimmed.isEmpty, !isSubmitting else { return }
        isSubmitting = true
        errorText = nil
        // On success, AuthGateView swaps this view out for the main shell, so we
        // only need to handle the FAILURE path here — otherwise the button would
        // spin on "Creating identity…" forever (the bug live-testing surfaced
        // when the Keychain was unavailable).
        Task { @MainActor in
            let ok = await authService.registerLocalIdentity(displayName: trimmed)
            if !ok {
                isSubmitting = false
                errorText = "Couldn't create your identity on this device. Please try again."
            }
        }
    }
}

